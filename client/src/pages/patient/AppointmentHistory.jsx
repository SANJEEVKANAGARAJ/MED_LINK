// ── Prescription PDF Document ──
const PrescriptionPDF = ({ record }) => {
  let meds = record.medications;
  if (typeof meds === 'string') { try { meds = JSON.parse(meds); } catch { meds = []; } }
  if (!Array.isArray(meds)) meds = [];

  return (
    <Document>
      <Page size="A4" style={pdfStyles.page}>
        <View style={pdfStyles.header}>
          <Text style={pdfStyles.title}>MedPortal · Prescription</Text>
          <Text style={pdfStyles.subtitle}>
            {format(new Date(record.appointment_date), 'MMMM d, yyyy')} · {record.slot_time?.substring(0, 5)}
          </Text>
        </View>

        <View style={pdfStyles.section}>
          <Text style={pdfStyles.sectionTitle}>Doctor</Text>
          <View style={pdfStyles.row}>
            <Text style={pdfStyles.label}>Name</Text>
            <Text style={pdfStyles.value}>Dr. {record.doctor_first_name} {record.doctor_last_name}</Text>
          </View>
          <View style={pdfStyles.row}>
            <Text style={pdfStyles.label}>Specialisation</Text>
            <Text style={pdfStyles.value}>{record.doctor_specialisation || 'N/A'}</Text>
          </View>
        </View>

        {record.prescription_notes && (
          <View style={pdfStyles.section}>
            <Text style={pdfStyles.sectionTitle}>Clinical Notes</Text>
            <View style={pdfStyles.box}>
              <Text>{record.prescription_notes}</Text>
            </View>
          </View>
        )}

        {meds.length > 0 && (
          <View style={pdfStyles.section}>
            <Text style={pdfStyles.sectionTitle}>Prescribed Medications</Text>
            <View style={{ ...pdfStyles.medRow, borderBottom: '2px solid #059669' }}>
              {['Medication', 'Dosage', 'Frequency', 'Duration'].map((h) => (
                <View key={h} style={pdfStyles.medCell}><Text style={{ fontWeight: 'bold', color: '#059669' }}>{h}</Text></View>
              ))}
            </View>
            {meds.filter(Boolean).map((med, i) => (
              <View key={i} style={pdfStyles.medRow}>
                <View style={pdfStyles.medCell}><Text>{med.medication_name}</Text></View>
                <View style={pdfStyles.medCell}><Text>{med.dosage}</Text></View>
                <View style={pdfStyles.medCell}><Text>{med.frequency}</Text></View>
                <View style={pdfStyles.medCell}><Text>{med.duration_days} days</Text></View>
              </View>
            ))}
          </View>
        )}

        {record.patient_friendly_summary && (
          <View style={pdfStyles.section}>
            <Text style={pdfStyles.sectionTitle}>AI Patient Summary</Text>
            <View style={pdfStyles.box}>
              <Text>{record.patient_friendly_summary}</Text>
            </View>
          </View>
        )}

        <Text style={pdfStyles.footer}>
          Generated by MedPortal · This is a digital prescription. Please consult your doctor for any questions.
        </Text>
      </Page>
    </Document>
  );
};

