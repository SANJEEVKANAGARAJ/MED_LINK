  row: { flexDirection: 'row', justifyContent: 'space-between', marginBottom: 4 },
  label: { color: '#64748b', width: '35%' },
  value: { color: '#1e293b', width: '65%', fontWeight: 'bold' },
  box: { backgroundColor: '#f0fdf4', border: '1px solid #bbf7d0', borderRadius: 4, padding: 10, marginTop: 8 },
  medRow: { flexDirection: 'row', borderBottom: '1px solid #e2e8f0', paddingVertical: 4 },
  medCell: { flex: 1, paddingRight: 4 },
