  invoiceAmount: { fontSize: 24, fontWeight: 'bold', color: '#059669', textAlign: 'center', marginTop: 10 },
  badge: { backgroundColor: '#dcfce7', color: '#166534', padding: '3 8', borderRadius: 4, fontSize: 9, alignSelf: 'flex-start' },
